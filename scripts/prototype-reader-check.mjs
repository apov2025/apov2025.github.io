import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const base = process.env.BASE_URL || 'http://127.0.0.1:5176';
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${base}/catalog/product/prototype/`);
  assert.equal(await page.locator('#reading-demo').count(), 1, 'Product includes the new reading simulator');
  await page.waitForFunction(() => document.querySelector('#viewer').dataset.viewerState === 'ready');
  await page.locator('#experience-mode').click();
  await page.waitForFunction(() => !document.querySelector('#reading-demo').hidden);
  const device = page.locator('#reader-device');
  const action = name => device.locator(`${['power', 'prev', 'next', 'menu'].includes(name) ? '.reader-hardware' : ''}[data-reader-action="${name}"]`);
  const state = () => device.getAttribute('data-reader-state');
  const position = () => device.getAttribute('data-reader-page');
  assert.equal(await state(), 'off');
  await action('next').click();
  assert.equal(await state(), 'off', 'Reading buttons do not power on');
  await action('power').click();
  assert.equal(await state(), 'boot');
  await page.waitForFunction(() => document.querySelector('#reader-device').dataset.readerState === 'library');
  await device.locator('[data-reader-book="0"]').click();
  assert.equal(await state(), 'reading');
  assert.equal(await position(), '0');
  const firstText = await device.locator('.reader-prose').innerText();
  assert.ok((await device.locator('.reader-touch').ariaSnapshot()).includes(firstText.slice(0, 40)), 'The accessible tree exposes actual book text');
  await action('prev').click();
  assert.equal(await position(), '0', 'First page cannot go backwards');
  await action('next').click();
  assert.equal(await position(), '1');
  assert.notEqual(await device.locator('.reader-prose').innerText(), firstText);
  const body = device.locator('.reader-touch');
  let box = await body.boundingBox();
  await body.click({ position: { x: box.width * .85, y: box.height * .5 } });
  assert.equal(await position(), '2', 'Touch right advances exactly once');
  await body.click({ position: { x: box.width * .1, y: box.height * .5 } });
  assert.equal(await position(), '1', 'Touch left returns one page');
  // A horizontal drag turns one page, without the following click turning another.
  box = await body.boundingBox();
  await page.mouse.move(box.x + box.width * .8, box.y + box.height * .5);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .15, box.y + box.height * .5, { steps: 8 });
  await page.mouse.up();
  assert.equal(await position(), '2');
  await action('prev').click();
  await action('power').click();
  assert.equal(await state(), 'sleep');
  await action('next').click();
  assert.equal(await state(), 'sleep');
  await action('power').click();
  assert.equal(await state(), 'reading');
  assert.equal(await position(), '1', 'Wake resumes reading');
  await action('menu').click();
  assert.equal(await state(), 'menu');
  await device.locator('[data-reader-size="large"]').click();
  await action('resume').click();
  const font = await device.locator('.reader-prose').evaluate(el => getComputedStyle(el).fontSize);
  assert.equal(font, '50px');
  assert.equal(await device.locator('.reader-prose').evaluate(el => el.scrollHeight <= el.clientHeight + 1), true, 'Reflow fits the screen');
  await action('next').click();
  const savedText = await device.locator('.reader-prose').innerText();
  await page.reload();
  await page.waitForFunction(() => !document.querySelector('#experience-mode').disabled);
  await page.locator('#experience-mode').click();
  await page.waitForFunction(() => !document.querySelector('#reading-demo').hidden);
  await action('power').click();
  await page.waitForFunction(() => document.querySelector('#reader-device').dataset.readerState === 'library');
  await device.locator('[data-reader-book="0"]').click();
  assert.equal(await device.locator('.reader-prose').innerText(), savedText, 'Reload preserves position and typography');
  await device.focus();
  await page.keyboard.press('ArrowRight');
  const keyboardPage = await position();
  await page.locator('#appearance-mode').focus();
  await page.keyboard.press('ArrowLeft');
  assert.equal(await position(), keyboardPage, 'Reader ignores keys outside its device');
  await page.locator('[data-language="zh-CN"]').click();
  assert.match(await device.locator('.reader-prose').innerText(), /[\u4e00-\u9fff]/);
  await page.locator('#explore').screenshot({ path: '/tmp/prototype-reader-desktop.png' });
  const preservedColors = await page.locator('[data-color-part]').evaluateAll(inputs => inputs.map(i => i.value));
  const preservedText = await device.locator('.reader-prose').innerText();
  await page.locator('#appearance-mode').click();
  await page.waitForFunction(() => !document.querySelector('#appearance-mode').disabled);
  assert.equal(await page.locator('#reading-demo').isVisible(), false);
  assert.equal(await page.locator('#random-colorway').isVisible(), true);
  await page.locator('#experience-mode').click();
  await page.waitForFunction(() => !document.querySelector('#reading-demo').hidden);
  assert.equal(await device.locator('.reader-prose').innerText(), preservedText);
  assert.deepEqual(await page.locator('[data-color-part]').evaluateAll(inputs => inputs.map(i => i.value)), preservedColors);
  const count = Number((await device.locator('.reader-page-number').innerText()).split('/')[1]);
  for (let i = 0; i < count + 2; i++) await action('next').click();
  assert.equal(Number(await position()), count - 1, 'Last page cannot advance beyond the book');
  await action('menu').click();
  await action('library').click();
  await device.locator('[data-reader-book="1"]').click();
  assert.equal(await position(), '0', 'Second book has independent progress');
  await action('menu').click();
  await action('shutdown').click();
  assert.equal(await state(), 'off');
  await action('power').click();
  await action('power').click();
  await page.waitForTimeout(900);
  assert.equal(await state(), 'off', 'Power during boot cancels startup');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
  await mobile.goto(`${base}/catalog/product/prototype/`);
  await mobile.waitForFunction(() => !document.querySelector('#experience-mode').disabled);
  await mobile.locator('#experience-mode').click();
  await mobile.waitForFunction(() => !document.querySelector('#reading-demo').hidden);
  const md = mobile.locator('#reader-device');
  await md.locator('[data-reader-action="power"]').tap();
  await mobile.waitForFunction(() => document.querySelector('#reader-device').dataset.readerState === 'library');
  await md.locator('[data-reader-book="0"]').tap();
  const touch = md.locator('.reader-touch');
  const rect = await touch.boundingBox();
  await mobile.touchscreen.tap(rect.x + rect.width * .85, rect.y + rect.height * .5);
  assert.equal(await md.getAttribute('data-reader-page'), '1');
  await mobile.setViewportSize({ width: 320, height: 740 });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.locator('#explore').screenshot({ path: '/tmp/prototype-reader-mobile.png' });
  const blocked = await browser.newPage();
  await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('Storage blocked'); } }); });
  await blocked.goto(`${base}/catalog/product/prototype/`);
  await blocked.waitForFunction(() => !document.querySelector('#experience-mode').disabled);
  await blocked.locator('#experience-mode').click();
  await blocked.waitForFunction(() => !document.querySelector('#reading-demo').hidden);
  await blocked.locator('.reader-hardware[data-reader-action="power"]').click();
  await blocked.waitForFunction(() => document.querySelector('#reader-device').dataset.readerState === 'library');
  await blocked.locator('[data-reader-book="0"]').click();
  assert.equal(await blocked.locator('#reader-device').getAttribute('data-reader-state'), 'reading', 'Reading works without storage');
  await blocked.close();
  assert.deepEqual(errors, []);
  console.log('PASS: power/boot, library, touch and hardware pagination, bounds, sleep/wake, typography reflow, persistence, keyboard isolation, languages and mobile touch.');
} finally { await browser.close(); }
